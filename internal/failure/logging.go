package failure

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"log/slog"
	"net"
	"sync/atomic"

	"github.com/go-sql-driver/mysql"
)

type requestKey struct{}
type requestState struct {
	id     string
	logged atomic.Int64
}

func NewRequest(ctx context.Context) context.Context {
	var bytes [16]byte
	// crypto/rand.Read is guaranteed to fill the buffer or terminate on Go 1.25.
	_, _ = rand.Read(bytes[:])
	return context.WithValue(ctx, requestKey{}, &requestState{id: "req_" + hex.EncodeToString(bytes[:])})
}
func RequestID(ctx context.Context) string {
	if state, ok := ctx.Value(requestKey{}).(*requestState); ok {
		return state.id
	}
	return ""
}

// Log records a failure once per request or tool invocation. Diagnostic fields
// are extracted by type; neither Error() strings nor upstream payloads are logged.
func Log(ctx context.Context, op string, err error, attrs ...any) {
	if err == nil {
		return
	}
	f := Describe(err)
	// 依据错误类别选择日志级别，业务拒绝保持 debug。
	level := slog.LevelDebug
	switch f.Code {
	case Internal:
		level = slog.LevelError
	case Unavailable, Upstream, Timeout, Capacity:
		level = slog.LevelWarn
	}
	if level == slog.LevelDebug && IsInfrastructure(err) && f.Code != Canceled {
		level = slog.LevelError
	}
	// Suppress repeated propagation of a failure, while allowing a later write
	// or infrastructure fault to remain visible after a business rejection.
	// 同一请求只记录最高严重级别的失败，避免传播链重复刷日志。
	if state, ok := ctx.Value(requestKey{}).(*requestState); ok {
		rank := int64(1)
		if level == slog.LevelWarn {
			rank = 2
		}
		if level == slog.LevelError {
			rank = 3
		}
		for {
			old := state.logged.Load()
			if old >= rank {
				return
			}
			if state.logged.CompareAndSwap(old, rank) {
				break
			}
		}
	}
	if op == "" {
		op = f.Op
	}
	fields := []any{"request_id", RequestID(ctx), "operation", op, "error_code", f.Code}
	if f.Op != "" {
		fields = append(fields, "failure_operation", f.Op)
	}
	fields = append(fields, Diagnostic(ctx, err)...)
	fields = append(fields, attrs...)
	slog.Log(ctx, level, "operation failed", fields...)
}

// Verbose 表示当前 logger 启用了 DEBUG/TRACE 级诊断。启用时允许输出原始错误文本。
func Verbose(ctx context.Context) bool {
	return slog.Default().Enabled(ctx, slog.LevelDebug)
}

// Diagnostic 按具体类型提取安全的诊断字段。默认不记录错误文本或上游载荷；
// 仅当 DEBUG/TRACE 级诊断启用时附带原始错误文本。
func Diagnostic(ctx context.Context, err error) []any {
	fields := []any{}
	var m *mysql.MySQLError
	if errors.As(err, &m) {
		fields = append(fields, "mysql_number", m.Number)
	}

	var j *json.SyntaxError
	if errors.As(err, &j) {
		fields = append(fields, "json_offset", j.Offset)
	}

	if f := Known(err); f != nil {
		if f.UpstreamStatus != 0 {
			fields = append(fields, "upstream_status", f.UpstreamStatus)
		}
		if f.Field != "" {
			fields = append(fields, "config_field", f.Field)
		}
	}
	if errors.Is(err, context.DeadlineExceeded) {
		fields = append(fields, "cause_kind", "deadline_exceeded")
	}
	if errors.Is(err, context.Canceled) {
		fields = append(fields, "cause_kind", "canceled")
	}
	var network net.Error
	if errors.As(err, &network) && network.Timeout() {
		fields = append(fields, "timeout", true)
	}
	// Bound traversal, including errors with an invalid cyclic Unwrap method.
	root := err
	causeOperation := ""
	for i := 0; i < 16; i++ {
		if f := Known(root); f != nil && f.Op != "" {
			causeOperation = f.Op
		}
		next := errors.Unwrap(root)
		if next == nil {
			break
		}
		root = next
	}
	if causeOperation != "" {
		fields = append(fields, "cause_operation", causeOperation)
	}
	// 原始错误文本仅在 DEBUG/TRACE 级诊断下输出，供启动与依赖故障排查。
	if Verbose(ctx) && root != nil {
		fields = append(fields, "error_text", root.Error())
	}
	return append(fields, "cause_type", fmt.Sprintf("%T", root))
}

// ValidRequestID accepts only the shape generated by this server, so optional
// transport metadata can never cause an arbitrary header value to enter logs.
func ValidRequestID(id string) bool {
	if len(id) != 36 || id[:4] != "req_" {
		return false
	}
	_, err := hex.DecodeString(id[4:])
	return err == nil
}

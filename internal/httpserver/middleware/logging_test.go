func TestRequestIdentityAndRouteLog(t *testing.T) {
	var output bytes.Buffer
	previous := slog.Default()
	slog.SetDefault(slog.New(slog.NewJSONHandler(&output, &slog.HandlerOptions{Level: slog.LevelDebug})))
	t.Cleanup(func() { slog.SetDefault(previous) })
	router := chi.NewRouter()
	// 服务端应生成请求 ID，忽略客户端伪造的同名头
	router.Get("/auth/interaction/{uid}", func(w http.ResponseWriter, r *http.Request) {
		id := failure.RequestID(r.Context())
		if id == "" || id == "client-secret" || r.Header.Get("X-Request-ID") != id || w.Header().Get("X-Request-ID") != id {
			t.Error("request identity was not generated by server")
		}
		w.WriteHeader(403)
	})
	r := httptest.NewRequest("GET", "/auth/interaction/private-id?token=secret", nil)
	r.Header.Set("X-Request-ID", "client-secret")
	w := httptest.NewRecorder()
	middleware.Logging(router).ServeHTTP(w, r)
	var entry map[string]any
	if err := json.Unmarshal(bytes.TrimSpace(output.Bytes()), &entry); err != nil {
		t.Fatal(err)
	}
	if entry["route"] != "/auth/interaction/{uid}" || entry["status"] != float64(403) || entry["request_id"] != w.Header().Get("X-Request-ID") || strings.Contains(output.String(), "private-id") || strings.Contains(output.String(), "secret") {
		t.Fatalf("invalid request log: %s", output.String())
	}
}

func TestRealMCPStreamingAndCancellation(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()

	// 用 channel 协调流式进度通知与取消传播
	canceled := make(chan struct{})
	progress := make(chan struct{}, 1)
	server := mcp.NewServer(&mcp.Implementation{Name: "stream-test", Version: "1"}, nil)
	mcp.AddTool(server, &mcp.Tool{Name: "wait", Description: "stream before cancellation"}, func(ctx context.Context, req *mcp.CallToolRequest, _ struct{}) (*mcp.CallToolResult, map[string]string, error) {
		if err := req.Session.NotifyProgress(ctx, &mcp.ProgressNotificationParams{ProgressToken: req.Params.GetProgressToken(), Progress: 1, Message: "ready"}); err != nil {
			return nil, nil, err
		}
		<-ctx.Done()
		close(canceled)
		return nil, nil, ctx.Err()
	})
	handler := mcp.NewStreamableHTTPHandler(func(*http.Request) *mcp.Server { return server }, &mcp.StreamableHTTPOptions{PropagateRequestCancellation: true})
	httpServer := httptest.NewServer(middleware.Logging(handler))
	defer httpServer.Close()
	client := mcp.NewClient(&mcp.Implementation{Name: "stream-client", Version: "1"}, &mcp.ClientOptions{ProgressNotificationHandler: func(context.Context, *mcp.ProgressNotificationClientRequest) { progress <- struct{}{} }})
	session, err := client.Connect(ctx, &mcp.StreamableClientTransport{Endpoint: httpServer.URL, HTTPClient: httpServer.Client(), DisableStandaloneSSE: true}, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer session.Close()
	callCtx, stop := context.WithCancel(ctx)
	defer stop()
	done := make(chan error, 1)
	params := &mcp.CallToolParams{Name: "wait", Arguments: map[string]any{}}
	params.SetProgressToken("progress-test")

	// 异步发起调用，应先收到进度通知而非等工具返回
	go func() { _, err := session.CallTool(callCtx, params); done <- err }()
	select {
	case <-progress:
	case <-ctx.Done():
		t.Fatal("stream notification was buffered until tool completion")
	}
	stop()
	select {
	case <-canceled:
	case <-ctx.Done():
		t.Fatal("cancellation did not reach server tool")
	}
	select {
	case err := <-done:
		if err == nil {
			t.Fatal("canceled call succeeded")
		}
	case <-ctx.Done():
		t.Fatal("client call did not stop")
	}
}
